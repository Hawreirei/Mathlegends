/**
 * Installable, offline game (#51): the web app manifest and the service worker, generated at
 * build time by the Vite plugin in vite.config.ts. Plain functions so tests/pwa.test.ts can
 * check them without a browser.
 */
import { createHash } from 'node:crypto';

export interface ManifestInput {
  base: string;
  name: string;
  description: string;
  lang: string;
  background: string;
  theme: string;
}

/** The web app manifest: what Android shows when the game is installed ("Add to Home screen"). */
export function manifest(m: ManifestInput): string {
  return JSON.stringify(
    {
      id: m.base,
      name: m.name,
      short_name: m.name,
      description: m.description,
      lang: m.lang,
      start_url: m.base,
      scope: m.base,
      // Full screen like a game; browsers that cannot fall back to a normal app window.
      display: 'fullscreen',
      display_override: ['fullscreen', 'standalone'],
      orientation: 'any',
      background_color: m.background,
      theme_color: m.theme,
      categories: ['education', 'games'],
      icons: [
        { src: `${m.base}icons/icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: `${m.base}icons/icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
        {
          src: `${m.base}icons/icon-maskable-512.png`,
          sizes: '512x512',
          type: 'image/png',
          purpose: 'maskable',
        },
        { src: `${m.base}icons/icon.svg`, sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
      ],
    },
    null,
    2,
  );
}

/**
 * Files the service worker stores on the first visit: everything the game needs to start and
 * play, relative to `base`. The `.woff` font fallbacks are left out: every browser with service
 * workers reads `.woff2`.
 */
export const precacheList = (files: readonly string[]): string[] =>
  ['', ...files.filter((f) => f !== 'index.html' && f !== 'sw.js' && !f.endsWith('.woff'))].sort();

/** A version that changes whenever any precached file name (all hashed) or index.html changes. */
export const cacheVersion = (files: readonly string[], indexHtml: string): string =>
  createHash('sha256').update(files.join('\n')).update(indexHtml).digest('hex').slice(0, 12);

/**
 * The service worker.
 * - Install: store every file in `files` (one cache per version), then take over at once.
 * - Pages (navigation): network first, so an online player always gets the newest version; offline,
 *   the stored page. Query strings (?fps) are ignored when looking it up.
 * - Lookups ignore `Vary`: scripts and fonts are requested with an Origin header (crossorigin),
 *   which a server's `Vary: Origin` would otherwise make miss the stored copy. Every stored file
 *   has a unique, hashed name, so this cannot serve the wrong one.
 * - Everything else under `base`: the stored copy first (file names are hashed, so a stored file
 *   never goes stale), else the network, storing what it returns.
 * - Activate: delete the caches of older versions.
 */
export function serviceWorker(base: string, files: readonly string[], version: string): string {
  return `// Generated by scripts/pwa.ts at build time (#51). Do not edit.
const CACHE = 'mathlegends-${version}';
const BASE = ${JSON.stringify(base)};
const FILES = ${JSON.stringify(files.map((f) => base + f))};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((k) => k.startsWith('mathlegends-') && k !== CACHE).map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(BASE, copy));
          }
          return res;
        })
        .catch(() => caches.match(BASE, { ignoreSearch: true, ignoreVary: true })),
    );
    return;
  }
  event.respondWith(
    caches.match(req, { ignoreSearch: true, ignoreVary: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
}
